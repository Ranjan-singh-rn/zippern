"""
Build a self-contained preview page for the generated Lottie assets.

    cd zipper-app && python3 tools/build_preview.py
    open tools/preview.html

Every animation is inlined into the HTML, so the page works by double-clicking
it — no local server. It uses the real lottie-web player from a CDN, which means
what you see here is what the app will render, not an approximation.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ANIM = os.path.join(HERE, "..", "app", "src", "main", "assets", "anim")
OUT = os.path.join(HERE, "preview.html")

GROUPS = [
    ("Avatar frames", "Worn around a user's photo. One per tier — bronze through cosmic.",
     ["frame_bronze", "frame_silver", "frame_gold", "frame_purple",
      "frame_royal", "frame_neon", "frame_galaxy", "frame_cosmic"]),
    ("Celebrations", "Fire once on an event: a combo gift, a lucky win, a level-up, a PK victory.",
     ["combo_burst", "lucky_win", "level_up", "pk_win"]),
    ("Entrances", "Sweep across the room when someone joins. Gated by level.",
     ["entrance_standard", "entrance_premium", "entrance_royal"]),
    ("Illustrated entrance",
     "Built from finished artwork rather than shapes — the drawing is embedded and flown. "
     "The wings do not flap; that needs an animator. For an entrance, this is usually enough.",
     ["entrance_dragon"]),
    ("Progress", "Fill 0 to 100%. Wish gifts, payout threshold, task targets.",
     ["wish_progress", "payout_progress"]),
    ("Surfaces", "A highlight sweeping across a card or bubble.",
     ["vip_shimmer", "bubble_shimmer"]),
]

anims, missing = {}, []
for _, _, names in GROUPS:
    for n in names:
        p = os.path.join(ANIM, n + ".json")
        if os.path.exists(p):
            anims[n] = json.load(open(p))
        else:
            missing.append(n)

cards = []
for title, blurb, names in GROUPS:
    items = ""
    for n in names:
        if n not in anims:
            continue
        d = anims[n]
        secs = d["op"] / d["fr"]
        kb = os.path.getsize(os.path.join(ANIM, n + ".json")) / 1024
        wide = " wide" if d["w"] > d["h"] * 1.6 else ""
        items += f"""
      <figure class="card{wide}">
        <div class="stage" id="s_{n}"></div>
        <figcaption>
          <b>{n}.json</b>
          <span>{d['w']}×{d['h']} · {secs:.2f}s · {kb:.1f} KB</span>
        </figcaption>
      </figure>"""
    cards.append(f"""
    <section>
      <h2>{title}</h2>
      <p class="blurb">{blurb}</p>
      <div class="grid">{items}</div>
    </section>""")

note = ""
if missing:
    note = ('<p class="warn">Missing (run <code>python3 tools/build_assets.py</code> first): '
            + ", ".join(missing) + "</p>")

html = f"""<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<title>Zipper — animated assets</title>
<script src="https://cdnjs.cloudflare.com/ajax/libs/bodymovin/5.12.2/lottie.min.js"></script>
<style>
  :root {{ color-scheme: dark; }}
  * {{ box-sizing: border-box; }}
  body {{
    margin: 0; padding: 48px 40px 80px;
    background: #070812; color: #fff;
    font: 15px/1.55 -apple-system, "Segoe UI", Roboto, sans-serif;
  }}
  h1 {{ font-size: 34px; letter-spacing: -.8px; margin: 0 0 6px; }}
  .lede {{ color: #9aa0bc; margin: 0 0 8px; max-width: 720px; }}
  .warn {{ color: #ffb627; }}
  section {{ margin-top: 52px; }}
  h2 {{ font-size: 19px; margin: 0 0 4px; }}
  .blurb {{ color: #6e7596; margin: 0 0 20px; font-size: 13.5px; }}
  .grid {{ display: flex; flex-wrap: wrap; gap: 18px; }}
  .card {{
    margin: 0; width: 208px;
    background: linear-gradient(180deg, rgba(255,255,255,.07), rgba(255,255,255,.02));
    border: 1px solid rgba(255,255,255,.09); border-radius: 16px;
    padding: 14px; transition: border-color .15s;
  }}
  .card:hover {{ border-color: rgba(255,61,139,.55); }}
  .card.wide {{ width: 434px; }}
  .stage {{
    height: 180px; border-radius: 11px; background: #0e0f21;
    display: flex; align-items: center; justify-content: center; overflow: hidden;
  }}
  .card.wide .stage {{ height: 120px; }}
  figcaption {{ margin-top: 11px; }}
  figcaption b {{ display: block; font-size: 13px; font-weight: 600; }}
  figcaption span {{ display: block; font-size: 11.5px; color: #6e7596; margin-top: 2px; }}
  .foot {{ margin-top: 64px; color: #6e7596; font-size: 13px; max-width: 720px; }}
  code {{ background: rgba(255,255,255,.08); padding: 1px 5px; border-radius: 4px; font-size: 12.5px; }}
</style></head><body>

<h1>Zipper — animated assets</h1>
<p class="lede">{len(anims)} Lottie animations, generated by <code>tools/build_assets.py</code>.
Rendered here with the real lottie-web player, so this is what the app will show.</p>
{note}
{''.join(cards)}

<div class="foot">
  <p>These are geometric effects — rings, glows, bursts, sweeps. Illustrated
  animation (a dragon, a car) still needs an animator; this covers everything else.</p>
  <p>To change a colour or add a tier, edit <code>tools/build_assets.py</code> and re-run it.
  Do not hand-edit the JSON.</p>
</div>

<script>
const DATA = {json.dumps(anims, separators=(',', ':'))};
for (const [name, data] of Object.entries(DATA)) {{
  const el = document.getElementById('s_' + name);
  if (!el) continue;
  lottie.loadAnimation({{
    container: el, renderer: 'svg', loop: true, autoplay: true, animationData: data
  }});
}}
</script>
</body></html>
"""

with open(OUT, "w") as f:
    f.write(html)

print(f"wrote {os.path.relpath(OUT, os.path.join(HERE, '..'))}  "
      f"({os.path.getsize(OUT)/1024:.0f} KB, {len(anims)} animations)")
if missing:
    print("missing:", ", ".join(missing))
print("\nopen it with:  open tools/preview.html")
