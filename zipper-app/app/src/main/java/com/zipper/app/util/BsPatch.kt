package com.zipper.app.util

import org.apache.commons.compress.compressors.bzip2.BZip2CompressorInputStream
import java.io.BufferedInputStream
import java.io.BufferedOutputStream
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.io.IOException
import java.io.InputStream
import java.io.OutputStream
import java.io.RandomAccessFile

/**
 * Applies a classic bsdiff (BSDIFF40) binary patch.
 *
 * ── WHY A BINARY PATCH AT ALL ────────────────────────────────────────────────
 *
 * The OTA APK is ~90 MB. Between two consecutive builds the ~50 MB of Agora and
 * TensorFlow native libraries are byte-identical and only part of the ~27 MB of
 * dex changes, so the honest difference between build N and build N+1 is single
 * digit megabytes. Sending the whole 90 MB every time bills the user's data plan
 * for bytes they already have on the handset.
 *
 * ── THE FORMAT, EXACTLY ──────────────────────────────────────────────────────
 *
 *   offset 0   : "BSDIFF40"                      8 bytes, ASCII
 *   offset 8   : length of the bzip2 control block   8 bytes, see [offtin]
 *   offset 16  : length of the bzip2 diff block      8 bytes, see [offtin]
 *   offset 24  : size of the reconstructed file      8 bytes, see [offtin]
 *   offset 32  : bzip2 stream — control
 *   offset 32 + ctrlLen          : bzip2 stream — diff
 *   offset 32 + ctrlLen + diffLen: bzip2 stream — extra
 *
 * The control stream is a sequence of triples (x, y, z):
 *
 *   * read x bytes from the diff stream and add them BYTEWISE, MODULO 256, to
 *     the x bytes of the old file at `oldpos`; write the sums,
 *   * copy y bytes verbatim from the extra stream,
 *   * `oldpos += z`, where z may be negative.
 *
 * Bytes of the old file outside `[0, oldSize)` contribute nothing — the diff
 * byte is written as-is. That is not a nicety: a patch that grows a file
 * legitimately addresses past the end of the old one, and treating that as an
 * error would reject valid patches. This matches bspatch.c's
 * `if ((oldpos + i >= 0) && (oldpos + i < oldsize))`.
 *
 * ── NOTHING IN HERE DECIDES ANYTHING ─────────────────────────────────────────
 *
 * This object reconstructs bytes and throws if the patch is not self-consistent.
 * It does NOT verify the result — it cannot, because it has no idea what the
 * result is supposed to hash to. The caller
 * ([com.zipper.app.util.ApkInstaller]) checks the reconstructed APK against the
 * published SHA-256 of the full APK, and that check is what makes the whole
 * scheme safe: it is the only proof that the installed APK really was the file
 * the patch was generated against. See ApkInstaller for why any failure here is
 * an optimisation that did not pay off rather than an error anybody is shown.
 */
object BsPatch {

    /** The eight ASCII bytes every BSDIFF40 patch starts with. */
    const val MAGIC: String = "BSDIFF40"

    /** Magic (8) + three [offtin] integers (24). */
    const val HEADER_BYTES: Int = 32

    /**
     * Read one bsdiff off_t: eight little-endian bytes, SIGN-MAGNITUDE.
     *
     * ── THIS IS NOT TWO'S COMPLEMENT AND THE DIFFERENCE IS SILENT ───────────
     *
     * bsdiff writes an offset as its MAGNITUDE in the low 63 bits, with bit 63
     * of the last byte as a separate sign flag. So `ff ff ff ff ff ff ff ff` is
     * -(2^63 - 1) here, where a two's-complement reader would call it -1.
     *
     * Every non-negative value is identical under both readings, which is
     * exactly what makes getting this wrong so dangerous: a two's-complement
     * implementation passes every test built from positive numbers, ships, and
     * then corrupts the first patch that happens to contain a backwards seek —
     * producing an APK that is wrong rather than one that fails to build. The
     * SHA-256 check on the result is the backstop, but the arithmetic should be
     * right on its own.
     *
     * Range is therefore [-(2^63 - 1), 2^63 - 1]; [Long.MIN_VALUE] is not
     * representable and can never come out of here. The byte pattern for
     * "negative zero" (sign set, magnitude 0) reads as 0, as it does in
     * bspatch.c.
     */
    fun offtin(buf: ByteArray, offset: Int = 0): Long {
        // Bit 63 is the sign flag, so it is masked off before it can be read as
        // part of the number.
        var y = buf[offset + 7].toLong() and 0x7FL
        for (i in 6 downTo 0) {
            y = (y shl 8) or (buf[offset + i].toLong() and 0xFFL)
        }
        return if (buf[offset + 7].toInt() and 0x80 != 0) -y else y
    }

    /**
     * The inverse of [offtin]: write [value] as eight sign-magnitude bytes.
     *
     * Present so the round trip can be pinned by a test rather than argued
     * about. The app never writes a patch — patches are generated by the publish
     * side — but an encoder that disagrees with the decoder is exactly the bug
     * that would not show up until a real negative seek arrived, and a test that
     * only ever reads bytes it did not produce cannot catch it.
     *
     * @throws IllegalArgumentException for [Long.MIN_VALUE], whose magnitude
     *   (2^63) does not fit in the 63 bits the format gives it. bsdiff has the
     *   same limit; failing loudly here beats writing a value that would read
     *   back as its own negation.
     */
    fun offtout(value: Long, buf: ByteArray, offset: Int = 0) {
        require(value != Long.MIN_VALUE) { "off_t magnitude 2^63 is not representable in a bsdiff offset" }
        var y = if (value < 0L) -value else value
        for (i in 0 until 8) {
            buf[offset + i] = (y and 0xFFL).toByte()
            y = y ushr 8
        }
        if (value < 0L) buf[offset + 7] = (buf[offset + 7].toInt() or 0x80).toByte()
    }

    /** [offtout] into a fresh eight-byte array. */
    fun offtout(value: Long): ByteArray = ByteArray(8).also { offtout(value, it, 0) }

    /**
     * Reconstruct [newFile] from [oldFile] and [patchFile].
     *
     * ── MEMORY: THE OLD FILE IS NEVER READ INTO AN ARRAY ────────────────────
     *
     * bspatch.c mallocs the old file and the new file whole. Doing that here
     * would be ~90 MB plus ~90 MB of Java heap on handsets whose whole per-app
     * heap limit is commonly 192–256 MB — an OutOfMemoryError on exactly the
     * cheap devices this feature exists to save data for, and it would strike
     * after the patch had already been downloaded.
     *
     * So the old APK is read through a [RandomAccessFile] (seek + read the one
     * window each control triple actually needs) and the result goes straight
     * out through a [BufferedOutputStream]. Peak heap is the three fixed
     * [BUFFER_BYTES] arrays plus whatever bzip2 holds internally — low
     * megabytes, independent of how big the APK is.
     *
     * Reading the old file in `oldpos` order rather than sequentially means the
     * seeks are not monotonic, which on flash storage costs nothing worth
     * measuring and is what buys the memory ceiling.
     *
     * @param onProgress called with (bytes written, total bytes) as the new file
     *   is built, at most once per [PROGRESS_STEP_BYTES]. Suspending so the
     *   caller can emit into a Flow directly; because that emission is itself a
     *   cancellable suspension point, it is also what makes a long apply
     *   cancellable when the user dismisses the dialog.
     * @return the number of bytes written, which is the patch header's declared
     *   new-file size.
     * @throws IOException if the patch is not a BSDIFF40 patch, is truncated, or
     *   is internally inconsistent.
     */
    suspend fun apply(
        oldFile: File,
        patchFile: File,
        newFile: File,
        onProgress: suspend (written: Long, total: Long) -> Unit = { _, _ -> },
    ): Long {
        val header = ByteArray(HEADER_BYTES)
        FileInputStream(patchFile).use { readFully(it, header, 0, HEADER_BYTES) }

        for (i in 0 until 8) {
            if (header[i] != MAGIC[i].code.toByte()) throw IOException("Not a BSDIFF40 patch")
        }

        val ctrlLen = offtin(header, 8)
        val diffLen = offtin(header, 16)
        val newSize = offtin(header, 24)
        if (ctrlLen < 0L || diffLen < 0L || newSize < 0L) {
            throw IOException("Corrupt patch header: ctrl=$ctrlLen diff=$diffLen new=$newSize")
        }
        // The extra block is whatever is left, so it needs no length — but the
        // first two blocks must fit inside the file we actually have. Checked
        // before any stream is opened so a truncated download fails here rather
        // than as a confusing bzip2 error two blocks in.
        val patchLen = patchFile.length()
        if (HEADER_BYTES + ctrlLen + diffLen > patchLen) {
            throw IOException("Truncated patch: header claims ${HEADER_BYTES + ctrlLen + diffLen} bytes, file is $patchLen")
        }

        val diffBuf = ByteArray(BUFFER_BYTES)
        val oldBuf = ByteArray(BUFFER_BYTES)
        val ctrlBuf = ByteArray(24)

        return RandomAccessFile(oldFile, "r").use { old ->
            val oldSize = old.length()
            bzip2At(patchFile, HEADER_BYTES.toLong()).use { control ->
                bzip2At(patchFile, HEADER_BYTES + ctrlLen).use { diff ->
                    bzip2At(patchFile, HEADER_BYTES + ctrlLen + diffLen).use { extra ->
                        BufferedOutputStream(FileOutputStream(newFile), BUFFER_BYTES).use { out ->
                            var oldPos = 0L
                            val reporter = Reporter(newSize, onProgress)
                            reporter.start()

                            while (reporter.written < newSize) {
                                readFully(control, ctrlBuf, 0, 24)
                                val diffCount = offtin(ctrlBuf, 0)
                                val extraCount = offtin(ctrlBuf, 8)
                                val seek = offtin(ctrlBuf, 16)

                                // Lengths are counts, never negative. `seek` IS
                                // allowed to be negative — that is the whole
                                // reason offtin has to be sign-magnitude.
                                if (diffCount < 0L || extraCount < 0L) {
                                    throw IOException("Corrupt control block: diff=$diffCount extra=$extraCount")
                                }
                                // Written as a subtraction rather than
                                // `written + diffCount > newSize` so a hostile
                                // length near Long.MAX_VALUE cannot overflow the
                                // comparison into passing.
                                if (diffCount > newSize - reporter.written) {
                                    throw IOException("Control block overruns the declared new size")
                                }

                                addDiff(old, oldSize, oldPos, diff, out, diffCount, diffBuf, oldBuf, reporter)
                                oldPos += diffCount

                                if (extraCount > newSize - reporter.written) {
                                    throw IOException("Control block overruns the declared new size")
                                }
                                copy(extra, out, extraCount, diffBuf, reporter)

                                oldPos += seek
                            }

                            out.flush()
                            reporter.finish()
                            // Value of the innermost `use`, and so of every
                            // enclosing one, and so of this function. A
                            // non-local `return` through four inline lambdas
                            // would work too but leaves the compiler inferring
                            // `Nothing` for four type arguments to say so.
                            newSize
                        }
                    }
                }
            }
        }
    }

    /**
     * A bzip2 stream starting at [offset] inside [file].
     *
     * The three blocks are concatenated in one file, so the decompressor must
     * stop at the end of the first stream it sees rather than rolling on into
     * the next one. `BZip2CompressorInputStream(stream)` does exactly that;
     * the two-argument constructor with `decompressConcatenated = true` would
     * silently splice the control block into the diff block.
     *
     * commons-compress rather than a hand-written bzip2 decoder or an NDK build
     * of libbz2: bzip2 is not in the Java standard library, this one is pure
     * Java, and anything native would mean a new .so per ABI in an APK whose
     * size is the entire problem being solved.
     */
    private fun bzip2At(file: File, offset: Long): InputStream {
        val raw = FileInputStream(file)
        return try {
            raw.channel.position(offset)
            BZip2CompressorInputStream(BufferedInputStream(raw, BUFFER_BYTES))
        } catch (t: Throwable) {
            // The wrapper never got built, so `use` will never close this.
            raw.close()
            throw t
        }
    }

    /**
     * Write [count] bytes: diff stream plus the old file at [oldStart], added
     * bytewise modulo 256.
     *
     * `(a + b).toByte()` is the modulo: Kotlin widens both bytes to Int, and
     * `toByte()` keeps the low 8 bits — which is addition mod 256, including
     * the wraparound the format depends on.
     */
    private suspend fun addDiff(
        old: RandomAccessFile,
        oldSize: Long,
        oldStart: Long,
        diff: InputStream,
        out: OutputStream,
        count: Long,
        diffBuf: ByteArray,
        oldBuf: ByteArray,
        reporter: Reporter,
    ) {
        var remaining = count
        var pos = oldStart
        while (remaining > 0L) {
            val n = minOf(remaining, BUFFER_BYTES.toLong()).toInt()
            readFully(diff, diffBuf, 0, n)

            // Anything outside the old file contributes zero — see the class
            // comment. Zeroing first means the intersection is the only part
            // that has to be read.
            oldBuf.fill(0, 0, n)
            val from = maxOf(pos, 0L)
            val to = minOf(pos + n, oldSize)
            if (to > from) {
                old.seek(from)
                old.readFully(oldBuf, (from - pos).toInt(), (to - from).toInt())
            }

            for (i in 0 until n) {
                diffBuf[i] = (diffBuf[i] + oldBuf[i]).toByte()
            }
            out.write(diffBuf, 0, n)

            pos += n
            remaining -= n
            reporter.advance(n)
        }
    }

    /** Copy [count] bytes verbatim from the extra stream. */
    private suspend fun copy(
        extra: InputStream,
        out: OutputStream,
        count: Long,
        buf: ByteArray,
        reporter: Reporter,
    ) {
        var remaining = count
        while (remaining > 0L) {
            val n = minOf(remaining, buf.size.toLong()).toInt()
            readFully(extra, buf, 0, n)
            out.write(buf, 0, n)
            remaining -= n
            reporter.advance(n)
        }
    }

    /**
     * Counts bytes written and reports them, no more often than every
     * [PROGRESS_STEP_BYTES].
     *
     * ── WHY THIS IS NOT COUNTED PER CONTROL TRIPLE ──────────────────────────
     *
     * The obvious place to report progress is once per control triple, and it
     * would be wrong here. Between two builds of this app the ~50 MB of Agora
     * and TensorFlow native libraries are byte-identical, and bsdiff encodes a
     * long identical run as ONE triple with a 50 MB diff length and all-zero
     * diff bytes. Reporting per triple would therefore leave the bar motionless
     * through more than half the work — which is exactly the frozen-at-100%
     * appearance the "Applying" step exists to avoid.
     *
     * So the count is advanced per 64 KB chunk instead, and throttled here. The
     * throttle matters as much as the counting: 90 MB in 64 KB chunks is ~1400
     * reports, each of which would recompose the dialog.
     *
     * [advance] is also the only suspension point in a long apply, which makes
     * it the only place a cancelled dialog can stop the work — the caller's
     * report lambda emits into a Flow, and that emission is cancellable.
     */
    private class Reporter(
        private val total: Long,
        private val onProgress: suspend (written: Long, total: Long) -> Unit,
    ) {
        var written: Long = 0L
            private set

        private var reportedAt = 0L

        suspend fun start() = onProgress(0L, total)

        suspend fun advance(n: Int) {
            written += n
            if (written - reportedAt >= PROGRESS_STEP_BYTES) {
                reportedAt = written
                onProgress(written, total)
            }
        }

        /** The final report, so the bar always reaches the end it was drawn to. */
        suspend fun finish() = onProgress(written, total)
    }

    /**
     * Read exactly [len] bytes or throw.
     *
     * `InputStream.read` is allowed to return short, and
     * [BZip2CompressorInputStream] genuinely does at block boundaries. A single
     * unchecked `read()` would leave stale bytes in the buffer and produce a
     * corrupt file rather than an exception.
     */
    private fun readFully(input: InputStream, buf: ByteArray, offset: Int, len: Int) {
        var done = 0
        while (done < len) {
            val n = input.read(buf, offset + done, len - done)
            if (n < 0) throw IOException("Patch stream ended after $done of $len bytes")
            done += n
        }
    }

    /**
     * 64 KB, the same chunk ApkInstaller hashes in. Big enough that the
     * per-read overhead disappears, small enough that three of them are noise
     * against any device's heap.
     */
    private const val BUFFER_BYTES = 64 * 1024

    /**
     * Report progress every megabyte of output. On a ~90 MB APK that is ~90
     * updates — enough that the bar visibly moves, few enough that the UI is not
     * recomposed fourteen hundred times.
     */
    private const val PROGRESS_STEP_BYTES = 1024L * 1024L
}
