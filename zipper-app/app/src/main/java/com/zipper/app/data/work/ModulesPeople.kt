package com.zipper.app.data.work

/*
 * Users, hosts and live rooms. Lists come from Firestore exactly as the CRM
 * reads them (`users` is listable by staff only — firestore.rules isStaff()),
 * and every decision goes through the API routes the CRM calls.
 */

private fun uidParam() = Input("uid", "Account ID (uid)", minLen = 1, maxLen = 128)

