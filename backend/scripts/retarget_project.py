"""Point the whole repo at a new Firebase project.

    python -m scripts.retarget_project \
        --project-id zipper-live-xxxx \
        --project-number 123456789012 \
        --bucket zipper-live-xxxx.firebasestorage.app          # dry run

    ... --confirm                                              # write it

Or, once the new `zipper-app/app/google-services.json` is in place, let the file
supply all three plus the Android Google Sign-In client id:

    python -m scripts.retarget_project --from-google-services

Rewrites the old project id, project number, storage bucket and Hosting URLs
across every text file in the repo. `.firebaserc` and `firebase.json` are
handled as JSON rather than as text, because they need structure changed and
not only strings swapped: the Firestore region moves to asia-south1 and the
`hosting` block becomes an array with a target, which is what DEPLOYMENT.md § 1
requires for a named Hosting site.

Two kinds of value are deliberately NOT invented:

  Downloaded files — `serviceAccountKey.json` and `google-services.json` are
  minted by Firebase and carry a private key, OAuth client ids and certificate
  hashes. There is no correct way to rewrite them. They are detected and named,
  and you download the new ones.

  Minted identifiers — the web API key, the Firebase app id (`1:<num>:web:<hash>`)
  and the OAuth client id (`<num>-<hash>.apps.googleusercontent.com`) all contain
  a project-specific hash. Swapping the project number inside one produces a
  string that looks right and does not exist, which is worse than leaving it
  alone. Lines holding one are left untouched and listed, unless you pass the
  real new value with --web-api-key / --web-app-id / --web-client-id.

Never touches backend/backups/, node_modules, .git, .venv or build output.
"""

