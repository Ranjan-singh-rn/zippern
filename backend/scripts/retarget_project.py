# ── Minted identifiers: project-specific hashes we cannot compute ─────────────

# label, pattern, flag, attribute, "carries the project number?"
#
# The first two contain the old project number, so a literal is provably from
# the old project. The last two are opaque, so a match only counts as old if the
# file it sits in also names the old project — which is true of every config
# file that holds one, and false of prose that happens to look similar.
MINTED = [
    (
        "OAuth client id (Android Google Sign-In)",
        re.compile(r"\d{6,}-[a-z0-9]{10,}\.apps\.googleusercontent\.com"),
        "--web-client-id",
        "web_client_id",
        True,
    ),
    (
        "Firebase web app id",
        re.compile(r"1:\d{6,}:web:[0-9a-zA-Z]+"),
        "--web-app-id",
        "web_app_id",
        True,
    ),
    (
        "Firebase Android app id",
        re.compile(r"1:\d{6,}:(?:android|ios):[0-9a-zA-Z]+"),
        "--android-app-id",
        "android_app_id",
        True,
    ),
    (
        # Classified below into the web key and the Android key by which file
        # it sits in. They are different values and swapping one for the other
        # is a silent failure at sign-in time.
        "API key",
        re.compile(r"AIza[0-9A-Za-z_\-]{30,}"),
        "--web-api-key",
        "web_api_key",
        False,
    ),
    (
        "Analytics measurement id (read by nothing in this repo)",
        re.compile(r"\bG-[A-Z0-9]{6,}\b"),
        "--measurement-id",
        "measurement_id",
        False,
    ),
]

AUTH_DOMAIN_LINE = re.compile(r"AUTH_DOMAIN|authDomain", re.IGNORECASE)


def find_minted(bodies: dict[str, str], a: argparse.Namespace) -> dict[str, tuple[str, str, str | None]]:
    """Every old minted literal in the repo → (label, flag, replacement or None).

    Scanned across the downloaded files too: google-services.json is the
    authoritative list of the old project's OAuth client ids, and it is read
    here even though it is never written.
    """
    found: dict[str, tuple[str, str, str | None]] = {}
    where: dict[str, set[str]] = {}

    for path, body in bodies.items():
        names_old = OLD_PROJECT_ID in body or OLD_PROJECT_NUMBER in body
        for label, pattern, flag, attr, carries_number in MINTED:
            for match in pattern.finditer(body):
                literal = match.group(0)
                if carries_number:
                    # Provably the old project's — its number is inside.
                    if OLD_PROJECT_NUMBER not in literal:
                        continue
                elif not names_old:
                    # Opaque. Only counts as old if this file names the old
                    # project. Keeps base64 inside a Lottie file out of it.
                    continue
                found.setdefault(literal, (label, flag, getattr(a, attr)))
                where.setdefault(literal, set()).add(path)

    # An AIza key found in google-services.json is the Android key; the one in
    # the CRM's env is the web key. ZIPPERN_SETUP_GUIDE.md quotes the Android
    # key under a web variable name, which is how they end up side by side.
    android_source = "zipper-app/app/google-services.json"
    for literal, (label, _flag, _repl) in list(found.items()):
        if label != "API key":
            continue
        if android_source in where.get(literal, set()):
            found[literal] = ("Android API key", "--android-api-key", a.android_api_key)
        else:
            found[literal] = ("web API key", "--web-api-key", a.web_api_key)

    return found


# ── Walking the tree ──────────────────────────────────────────────────────────


def rel(path: Path) -> str:
    return path.relative_to(REPO).as_posix()


def is_skipped(path: Path) -> bool:
    r = rel(path)
    if r in SKIP_FILES:
        return True
    for part in path.relative_to(REPO).parts[:-1]:
        if part in SKIP_DIR_NAMES:
            return True
    for prefix in SKIP_PATHS:
        if r == prefix or r.startswith(prefix + "/"):
            return True
    return path.suffix.lower() in SKIP_SUFFIXES


def text_files() -> list[Path]:
    out: list[Path] = []
    for path in sorted(REPO.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        if is_skipped(path):
            continue
        try:
            if path.stat().st_size > 5_000_000:
                continue
        except OSError:
            continue
        out.append(path)
    return out


def read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return None


# ── The rewrite ───────────────────────────────────────────────────────────────


class Plan:
    """Everything the run decided, so it can be printed once at the end."""

    def __init__(self) -> None:
        self.changed: list[tuple[str, int, str]] = []   # path, count, note
        self.leftovers: list[tuple[str, int, str, str]] = []  # path, line, what, flag
        self.downloads: list[str] = []


def rewrite_line(
    line: str,
    a: argparse.Namespace,
    minted: dict[str, tuple[str, str, str | None]],
) -> tuple[str, int, list[tuple[str, str]]]:
    """Rewrite one line. Returns the line, how many swaps, and anything skipped."""
    swaps = 0
    skipped: list[tuple[str, str]] = []

    # A line carrying a hash we cannot compute is left whole. Rewriting the
    # project number inside `344965230552-egtr….apps.googleusercontent.com`
    # would mint a client id that does not exist, and the failure would not
    # surface until a user tapped "Continue with Google".
    protected = False
    for literal, (label, flag, replacement) in minted.items():
        if literal not in line:
            continue
        if replacement:
            line = line.replace(literal, replacement)
            swaps += 1
            continue
        skipped.append((label, flag))
        protected = True

    # 1. Storage bucket, including gs:// forms.
    if OLD_BUCKET in line:
        line = line.replace(OLD_BUCKET, a.bucket)
        swaps += 1

    # 2. Auth domain is project-scoped, not hosting-scoped. `authDomain` must be
    #    <project>.firebaseapp.com — it is where the Firebase Auth handler lives.
    #    Every other .firebaseapp.com in the repo is a link to the CRM.
    if AUTH_DOMAIN_LINE.search(line):
        old = f"{OLD_PROJECT_ID}.firebaseapp.com"
        if old in line:
            line = line.replace(old, f"{a.project_id}.firebaseapp.com")
            swaps += 1

    # 3. Hosting URLs move to the named site, not to the new project id — that
    #    is the whole point of creating the `zipper` site.
    for suffix in (".web.app", ".firebaseapp.com"):
        old = f"{OLD_PROJECT_ID}{suffix}"
        if old in line:
            line = line.replace(old, f"{a.hosting_site}{suffix}")
            swaps += 1

    # 4. Bare project number and project id.
    if not protected:
        if OLD_PROJECT_NUMBER in line:
            line = line.replace(OLD_PROJECT_NUMBER, a.project_number)
            swaps += 1
    if OLD_PROJECT_ID in line:
        line = line.replace(OLD_PROJECT_ID, a.project_id)
        swaps += 1

    return line, swaps, skipped


def rewrite_text(
    path: Path,
    body: str,
    a: argparse.Namespace,
    plan: Plan,
    minted: dict[str, tuple[str, str, str | None]],
) -> tuple[str, int]:
    out: list[str] = []
    total = 0
    for n, line in enumerate(body.splitlines(keepends=True), start=1):
        new_line, swaps, skipped = rewrite_line(line, a, minted)
        for label, flag in skipped:
            plan.leftovers.append((rel(path), n, label, flag))
        out.append(new_line)
        total += swaps
    return "".join(out), total


# ── The two files that need structure changed, not strings swapped ────────────


def build_firebaserc(a: argparse.Namespace) -> str:
    return json.dumps(
        {
            "projects": {"default": a.project_id},
            "targets": {
                a.project_id: {"hosting": {"production": [a.hosting_site]}}
            },
            "etags": {},
        },
        indent=2,
    ) + "\n"


def build_firebase_json(a: argparse.Namespace, body: str) -> tuple[str, list[str]]:
    cfg = json.loads(body)
    notes: list[str] = []

    fs = cfg.get("firestore")
    if isinstance(fs, dict) and fs.get("location") != a.firestore_region:
        notes.append(f"firestore.location {fs.get('location')} → {a.firestore_region}")
        fs["location"] = a.firestore_region

    # ── Storage: two shapes, and only one of them names a bucket ────────────
    #
    # `firebase.json` used to declare storage as the ARRAY (multi-bucket) form,
    # `[{bucket, rules}]`, and this loop rewrote the bucket on each entry. It
    # is now the single-object form, `{rules}`, because the array form binds to
    # a deploy TARGET that was never registered — see the `//storage` note in
    # firebase.json.
    #
    # Handled explicitly rather than left to fall through. `for entry in {...}`
    # iterates a dict's KEYS, so the old loop would have run over the string
    # "rules", failed `isinstance(entry, dict)`, and silently rewritten
    # nothing — a retarget that reports success and moves no bucket.
    #
    # The single-object form needs no rewrite at all: with no bucket named, the
    # rules follow the project's own default bucket, so pointing `.firebaserc`
    # at a new project is enough. That is said out loud in the notes, because
    # "nothing to change" and "the script did not look" read identically in a
    # diff.
    storage_cfg = cfg.get("storage")
    if isinstance(storage_cfg, list):
        for entry in storage_cfg:
            if isinstance(entry, dict) and entry.get("bucket") != a.bucket:
                notes.append(f"storage.bucket → {a.bucket}")
                entry["bucket"] = a.bucket
    elif isinstance(storage_cfg, dict):
        notes.append(
            "storage: single-object form names no bucket, so it follows the "
            f"new project's default ({a.bucket}) — nothing to rewrite"
        )

    hosting = cfg.get("hosting")
    if isinstance(hosting, dict):
        # DEPLOYMENT.md § 1: a named site needs a target, and a target needs the
        # hosting block to be an array. Left as an object, `firebase deploy`
        # ignores the target and publishes to <project>.web.app instead.
        cfg["hosting"] = [{"target": a.hosting_target, **hosting}]
        notes.append(f"hosting → array with target '{a.hosting_target}'")
    elif isinstance(hosting, list):
        for site in hosting:
            if isinstance(site, dict) and "target" not in site:
                site["target"] = a.hosting_target
                notes.append(f"hosting[] target '{a.hosting_target}' added")

    # Any remaining project-id string inside (there is none today, but a rewrite
    # that quietly skips is worse than one that is thorough).
    text = json.dumps(cfg, indent=2) + "\n"
    text = text.replace(f"{OLD_PROJECT_ID}.web.app", f"{a.hosting_site}.web.app")
    text = text.replace(OLD_PROJECT_ID, a.project_id)
    return text, notes


# ── Refusals ──────────────────────────────────────────────────────────────────


PROJECT_ID_RE = re.compile(r"^[a-z][a-z0-9-]{4,28}[a-z0-9]$")


def check(a: argparse.Namespace) -> list[str]:
    problems: list[str] = []

    if not a.project_id:
        problems.append("No --project-id given. There is nothing to move to.")
    elif a.project_id == OLD_PROJECT_ID:
        problems.append(
            f"--project-id is {OLD_PROJECT_ID}, which is the project you are\n"
            "    leaving. Nothing to do — check you copied the new one."
        )
    elif not PROJECT_ID_RE.match(a.project_id):
        problems.append(
            f"--project-id '{a.project_id}' is not a valid Firebase project id.\n"
            "    Lowercase letters, digits and hyphens, 6–30 characters, starting\n"
            "    with a letter. Copy it from the console rather than typing it."
        )

    if not a.project_number:
        problems.append("No --project-number given.")
    elif not a.project_number.isdigit():
        problems.append(f"--project-number '{a.project_number}' is not all digits.")
    elif a.project_number == OLD_PROJECT_NUMBER:
        problems.append(
            "--project-number is the old project's number. Firebase Console →\n"
            "    Project settings → General → Project number."
        )

    if not a.bucket:
        problems.append("No --bucket given.")
    elif a.bucket == OLD_BUCKET:
        problems.append("--bucket is the old bucket. Nothing would move.")
    elif a.project_id and not a.bucket.startswith(a.project_id + "."):
        problems.append(
            f"--bucket '{a.bucket}' does not begin with the new project id.\n"
            f"    Firebase names it '{a.project_id}.firebasestorage.app' (or\n"
            f"    '{a.project_id}.appspot.com' on older projects). Copy the exact\n"
            "    value from Console → Storage. Pass --allow-odd-bucket if you\n"
            "    really do mean a bucket named something else."
        )

    if a.hosting_site and "." in a.hosting_site:
        problems.append(
            f"--hosting-site '{a.hosting_site}' looks like a domain. It wants the\n"
            "    bare site id, e.g. 'zipper', not 'zipper.web.app'."
        )

    missing = [p for p in EXPECTED if not (REPO / p).exists()]
    if missing:
        problems.append(
            "Files this script expects are not there:\n"
            + "\n".join(f"      · {m}" for m in missing)
            + "\n    Either you are not in the zipper repo, or something was moved.\n"
            "    Nothing was read and nothing was written."
        )

    return problems


def load_google_services(path: Path) -> dict:
    """Pull the new identity out of a freshly downloaded google-services.json."""
    data = json.loads(path.read_text())
    info = data.get("project_info") or {}
    out = {
        "project_id": info.get("project_id"),
        "project_number": info.get("project_number"),
        "bucket": info.get("storage_bucket"),
        "web_client_id": None,
        "android_app_id": None,
        "android_api_key": None,
    }
    for client in data.get("client") or []:
        pkg = ((client.get("client_info") or {}).get("android_client_info") or {}).get(
            "package_name"
        )
        if pkg == ANDROID_PACKAGE:
            out["android_app_id"] = (client.get("client_info") or {}).get(
                "mobilesdk_app_id"
            )
            for key in client.get("api_key") or []:
                if key.get("current_key"):
                    out["android_api_key"] = key["current_key"]
                    break
        for oauth in client.get("oauth_client") or []:
            # client_type 3 is the *web* client — the one Android's
            # GetGoogleIdOption.setServerClientId() wants. Type 1 is the
            # Android client and is not what strings.xml holds.
            if oauth.get("client_type") == 3 and oauth.get("client_id"):
                out["web_client_id"] = oauth["client_id"]
                break
        if out["web_client_id"] and out["android_app_id"]:
            break
    return out


# ── Main ──────────────────────────────────────────────────────────────────────


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="python -m scripts.retarget_project",
        description="Point the repo at a new Firebase project.",
    )
    p.add_argument("--project-id", default=None)
    p.add_argument("--project-number", default=None)
    p.add_argument("--bucket", default=None)
    p.add_argument("--hosting-site", default="zipper",
                   help="Hosting site id — the CRM's subdomain. Default: zipper")
    p.add_argument("--hosting-target", default="production",
                   help="firebase.json hosting target name. Default: production")
    p.add_argument("--firestore-region", default="asia-south1")
    p.add_argument("--web-api-key", default=None,
                   help="The CRM's browser API key, from Console → Project "
                        "settings → Your apps → Web app.")
    p.add_argument("--android-api-key", default=None,
                   help="The Android API key. Filled in automatically by "
                        "--from-google-services.")
    p.add_argument("--web-app-id", default=None)
    p.add_argument("--android-app-id", default=None,
                   help="The 1:<num>:android:<hash> id, if the docs quote it.")
    p.add_argument("--web-client-id", default=None,
                   help="The <num>-<hash>.apps.googleusercontent.com web OAuth "
                        "client id, for Android Google Sign-In.")
    p.add_argument("--measurement-id", default=None)
    p.add_argument("--from-google-services", nargs="?",
                   const="zipper-app/app/google-services.json", default=None,
                   help="Read project id, number, bucket and OAuth client id from "
                        "a downloaded google-services.json.")
    p.add_argument("--allow-odd-bucket", action="store_true")
    p.add_argument("--confirm", action="store_true")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    a = parse_args(argv)

    if a.from_google_services:
        gs = REPO / a.from_google_services
        if not gs.exists():
            print(f"\n  ✗ {a.from_google_services} is not there.\n")
            return 1
        try:
            found = load_google_services(gs)
        except (json.JSONDecodeError, OSError) as exc:
            print(f"\n  ✗ Could not read {a.from_google_services}: {exc}\n")
            return 1
        if found["project_id"] == OLD_PROJECT_ID:
            print(
                f"\n  ✗ {a.from_google_services} still names {OLD_PROJECT_ID}.\n\n"
                "    That is the old file. Download the new one first —\n"
                "    Console → Project settings → Your apps → Android → \n"
                "    google-services.json — and put it at that same path.\n"
            )
            return 1
        for key, value in found.items():
            if value and getattr(a, key) is None:
                setattr(a, key, value)
        print(f"\n  Read the new identity from {a.from_google_services}")

    problems = check(a)
    if a.allow_odd_bucket:
        problems = [p for p in problems if "does not begin with the new project id" not in p]
    if problems:
        print("\n  ✗ Refusing to run.\n")
        for p in problems:
            head, *rest = p.splitlines()
            print(f"    · {head}")
            for line in rest:
                print(f"      {line.strip()}" if line.strip() else "")
            print()
        return 1

    print(f"\n  Retargeting the repo   {OLD_PROJECT_ID} → {a.project_id}")
    print(f"  {'WRITING' if a.confirm else 'DRY RUN — nothing will be written'}\n")
    print("  New identity")
    print(f"    · project id        {a.project_id}")
    print(f"    · project number    {a.project_number}")
    print(f"    · storage bucket    {a.bucket}")
    print(f"    · hosting site      {a.hosting_site}  →  https://{a.hosting_site}.web.app")
    print(f"    · auth domain       {a.project_id}.firebaseapp.com")
    print(f"    · firestore region  {a.firestore_region}")

    plan = Plan()

    # Read once. Everything below works off this map, so the tree is walked
    # a single time and the dry run reads exactly what the real run would.
    files = text_files()
    bodies: dict[str, str] = {}
    for path in files:
        body = read_text(path)
        if body is not None:
            bodies[rel(path)] = body

    minted = find_minted(bodies, a)

    # If two different API keys are in play, one --web-api-key cannot be right
    # for both. Do not guess which line gets it.
    web_keys = [lit for lit, (label, _f, _r) in minted.items() if label == "web API key"]
    if len(web_keys) > 1:
        print(
            f"\n  ✗ {len(web_keys)} different web API keys are in the repo:\n"
            + "\n".join(f"      {k[:10]}…" for k in sorted(web_keys))
            + "\n\n    One --web-api-key cannot be right for all of them, and putting\n"
            "    the wrong one somewhere fails at sign-in with no useful message.\n"
            "    Reconcile them against Console → Project settings → Your apps\n"
            "    first, then re-run.\n"
        )
        return 1

    for path in files:
        r = rel(path)

        if r in DOWNLOADED:
            plan.downloads.append(r)
            continue

        body = bodies.get(r)
        if body is None:
            continue

        if r == ".firebaserc":
            new = build_firebaserc(a)
            if new != body:
                plan.changed.append((r, 1, "rewritten — default project and hosting target"))
                if a.confirm:
                    path.write_text(new, encoding="utf-8")
            continue

        if r == "firebase.json":
            try:
                new, notes = build_firebase_json(a, body)
            except json.JSONDecodeError as exc:
                print(f"\n  ✗ firebase.json is not valid JSON ({exc}). Fix it first.\n")
                return 1
            if new != body:
                plan.changed.append((r, len(notes), "; ".join(notes) or "rewritten"))
                if a.confirm:
                    path.write_text(new, encoding="utf-8")
            continue

        if (
            OLD_PROJECT_ID not in body
            and OLD_PROJECT_NUMBER not in body
            and OLD_BUCKET not in body
            and not any(lit in body for lit in minted)
        ):
            continue

        new, count = rewrite_text(path, body, a, plan, minted)
        if new != body:
            plan.changed.append((r, count, f"{count} replacement(s)"))
            if a.confirm:
                path.write_text(new, encoding="utf-8")

    # ── Report ────────────────────────────────────────────────────────────────

    width = max((len(c[0]) for c in plan.changed), default=0)
    if plan.changed:
        print(f"\n  {'CHANGED' if a.confirm else 'WOULD CHANGE'}")
        for name, _count, note in plan.changed:
            print(f"    · {name:<{width}}  {note}")
    else:
        print("\n  Nothing to change — no file mentions the old project.")
        print("  Either this has already been run, or the arguments are wrong.\n")
        return 0

    if plan.downloads:
        print("\n  DOWNLOADED FILES — replace these by hand, they cannot be rewritten")
        for name in plan.downloads:
            print(f"    · {name}")
            print(f"        {DOWNLOADED[name]}")

    if plan.leftovers:
        print("\n  ⚠  STILL HOLDING OLD-PROJECT VALUES")
        print("     Each of these contains a hash only Firebase can mint. They were")
        print("     left exactly as they are rather than half-rewritten into a value")
        print("     that does not exist. Re-run with the flag named to fix them.\n")
        seen: set[tuple[str, str]] = set()
        for name, line, label, flag in plan.leftovers:
            print(f"    · {name}:{line}  {label}")
            seen.add((label, flag))
        print()
        for label, flag in sorted(seen):
            print(f"      {flag}  — {label}")

    total = sum(c[1] for c in plan.changed)
    if a.confirm:
        print(f"\n  {len(plan.changed)} file(s) changed, {total} replacement(s).")
        print("\n  Next, in order:")
        print("    1. Check the diff:            git diff")
        print("    2. Rebuild the CRM:           cd zipper-crm && npm run build")
        print("    3. Move the content assets:   python -m scripts.migrate_assets")
        print("    4. Then DEPLOYMENT.md, § by §, against the new project.\n")
    else:
        print(f"\n  {len(plan.changed)} file(s), {total} replacement(s) would change.")
        print("\n  Nothing has changed. To go ahead, add --confirm:")
        print("    python -m scripts.retarget_project " + " ".join(argv) + " --confirm\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
