/** firestore.rules `isOps() || isAdmin() || isSupport()` (feedbackTickets / supportTickets updates). */
private val ticketWorker: (Caps) -> Boolean = { c ->
    c.requireWrite && (c.isOwner || c.isTeamAdmin || c.role.startsWith("ops_") || c.role.startsWith("support_"))
}

/** `_require_oversight`: owner, observer or a team admin. */
